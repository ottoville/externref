

pub trait TextureFormatTrait {
    fn to_number() -> TextureFormat
    where
        Self: Sized;
}
pub struct BGRA8UNORM();
impl TextureFormatTrait for BGRA8UNORM {
    fn to_number() -> TextureFormat {
        TextureFormat::BGRA8UNORM
    }
}
pub struct R8UINT();
impl TextureFormatTrait for R8UINT {
    fn to_number() -> TextureFormat {
        TextureFormat::R8UINT
    }
}

