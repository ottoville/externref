const textureAspectMapping = {
  0: 'all',
  1: 'stencil-only',
  2: 'depth-only',
} as const;

export const TextureExports = {
  create_view(
    texture: GPUTexture,
    label_vec_ptr: rust_pointer<'label'>,
    format: keyof typeof textureFormatMapping,
    dimension: keyof typeof viewDimensionMapping,
    usage: number,
    aspect: keyof typeof textureAspectMapping,
    baseMipLevel: number,
    mipLevelCount: number,
    baseArrayLayer: number,
    arrayLayerCount: number,
  ): GPUTextureView {
    const label = stringFromPtr(engine.rust.memory, label_vec_ptr);

    return texture.createView({
      arrayLayerCount,
      aspect: textureAspectMapping[aspect],
      baseArrayLayer,
      baseMipLevel,
      dimension: viewDimensionMapping[dimension],
      format: textureFormatMapping[format],
      label,
      mipLevelCount,
      usage,
    });
  },
};
